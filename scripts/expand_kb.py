def main() -> None:
    symptoms = load("symptoms.json", "symptoms")
    medicines = load("medicines.json", "medicines")
    diseases = load("diseases.json", "diseases")

    have_sym = {s["id"] for s in symptoms}
    have_med = {m["id"] for m in medicines}
    have_dis = {d["id"] for d in diseases}

    added_sym = added_med = added_dis = 0

    for sid, label, system, syns, red, level, weight in NEW_SYMPTOMS:
        if sid in have_sym:
            continue
        symptoms.append({
            "id": sid, "label": label, "system": system, "synonyms": syns,
            "red_flag": red, "weight": weight, "red_flag_level": level,
        })
        have_sym.add(sid)
        added_sym += 1

    for med in NEW_MEDICINES:
        if med["id"] in have_med:
            continue
        medicines.append(med)
        have_med.add(med["id"])
        added_med += 1

    # Merge the extra phrasings, de-duplicating against what is already listed.
    patched = 0
    by_id = {s["id"]: s for s in symptoms}
    for sid, extra in SYNONYM_PATCH.items():
        entry = by_id.get(sid)
        if not entry:
            continue
        existing = {s.lower() for s in entry.get("synonyms", [])}
        for phrase in extra:
            if phrase.lower() not in existing:
                entry.setdefault("synonyms", []).append(phrase)
                existing.add(phrase.lower())
                patched += 1

    # Routines are referenced by id; refuse to add a disease that points at one
    # that does not exist rather than writing a broken row.
    routine_ids = set(load("routines.json", "routines"))

    for dis in NEW_DISEASES:
        did = dis["id"]
        if did in have_dis:
            continue
        for sid in list(dis["symptoms"]) + list(dis["key_symptoms"]):
            assert sid in have_sym, f"{did} references unknown symptom {sid}"
        for mid in dis["medicines"]:
            assert mid in have_med, f"{did} references unknown medicine {mid}"
        assert dis["routine"] in routine_ids, f"{did} references unknown routine {dis['routine']}"
        for key in dis["key_symptoms"]:
            assert key in dis["symptoms"], f"{did} key symptom {key} is not scored"
        assert all(w > 0 for w in dis["symptoms"].values()), f"{did} has a zero weight"
        assert dis["when_to_see_doctor"], f"{did} has no escalation advice"
        assert 1 <= dis["severity_score"] <= 10
        diseases.append(dis)
        have_dis.add(did)
        added_dis += 1

    save("symptoms.json", "symptoms", symptoms)
    save("medicines.json", "medicines", medicines)
    save("diseases.json", "diseases", diseases)

    print(f"added {added_sym} symptoms, {added_med} medicines, {added_dis} conditions, {patched} synonyms")
    print(f"totals: {len(symptoms)} symptoms, {len(medicines)} medicines, {len(diseases)} conditions")


if __name__ == "__main__":
    main()
