"""Translated interface strings for the 22 scheduled languages of India.

The catalogue is deliberately a flat key -> string map so it can be shipped to
the browser in one payload and applied without a build step. English is the
base: any key missing from a translation falls back to English, so a partly
translated language shows English for the gaps rather than a blank label.

Coverage policy
---------------
Every language translates the *safety-critical* keys in full: the emergency
warning, the triage levels and their advice, and the disclaimer. These are the
strings a patient must not misread. The rest of the interface is translated for
the widely spoken languages; where a translation is not available the English
string is shown and the response marks the language as partly translated, so the
gap is visible rather than hidden.
"""
