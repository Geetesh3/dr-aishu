def _load_overlay() -> dict[str, dict[str, str]]:
    """Merge the extended translation file into TRANSLATIONS.

    The base catalogue above carries the safety-critical set, which is reviewed
    in one place. The rest of the interface copy is larger and lives in
    ``data/translations_extra.json`` so it can be edited, reviewed and extended
    without touching code. Overlay values win, so a correction here can revise a
    base string too.
    """
    path = _DATA_DIR / "translations_extra.json"
    if not path.exists():
        return {}
    try:
        with path.open(encoding="utf-8") as fh:
            data = json.load(fh)
    except (OSError, ValueError):
        return {}
    if not isinstance(data, dict):
        return {}
    data.pop("_note", None)
    merged: dict[str, dict[str, str]] = {}
    for lang, table in data.items():
        if isinstance(table, dict):
            merged[lang] = {k: v for k, v in table.items() if isinstance(v, str)}
    return merged


for _lang, _table in _load_overlay().items():
    TRANSLATIONS.setdefault(_lang, {}).update(_table)


def t(key: str, lang: str = "en") -> str:
    """Resolve `key` for `lang`, falling back to English then to the key itself.

    English is the base catalogue, so a gap in a translation degrades to a
    readable English string rather than an empty label.
    """
    if lang and lang in TRANSLATIONS:
        value = TRANSLATIONS[lang].get(key)
        if value:
            return value
    return EN.get(key, key)


def bundle(lang: str) -> dict[str, str]:
    """The full resolved string table for a language, for the browser."""
    base = dict(EN)
    if lang and lang in TRANSLATIONS:
        base.update(TRANSLATIONS[lang])
    return base


def coverage(lang: str) -> dict[str, Any]:
    """How complete a language is, and whether its safety strings are present.

    `safety_complete` is the field that matters: a language may be partly
    translated and still be safe to offer, as long as every critical key is
    present. `complete` means the whole interface is translated.
    """
    if not lang or lang == "en":
        return {"code": "en", "translated_keys": len(EN), "total_keys": len(EN),
                "percent": 100.0, "safety_complete": True, "complete": True}
    table = TRANSLATIONS.get(lang, {})
    translatable = [key for key in EN if key not in BRAND_KEYS]
    translated = sum(1 for key in translatable if key in table)
    missing_critical = [key for key in CRITICAL_KEYS if key not in table]
    return {
        "code": lang,
        "translated_keys": translated,
        "total_keys": len(translatable),
        "percent": round(100.0 * translated / max(1, len(translatable)), 1),
        "safety_complete": not missing_critical,
        "missing_critical": missing_critical,
        "complete": translated >= len(translatable),
    }


def catalogue() -> dict[str, dict[str, Any]]:
    """Coverage for every language, for the picker and the API."""
    from .i18n import LANGUAGE_BY_CODE
    return {code: coverage(code) for code in LANGUAGE_BY_CODE}
